import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const rootDir = path.resolve(__dirname, '..');
const configJsonPath = path.join(rootDir, 'public', 'config.json');
const targetDir = path.join(rootDir, 'src', 'config');
const targetFile = path.join(targetDir, 'config.generated.ts');

if (!fs.existsSync(configJsonPath)) {
  console.error(`FATAL: Config file not found at ${configJsonPath}`);
  process.exit(1);
}

const rawConfig = fs.readFileSync(configJsonPath, 'utf-8');
let parsedConfig;

try {
  parsedConfig = JSON.parse(rawConfig);
} catch (err) {
  console.error(`FATAL: Failed to parse public/config.json:`, err);
  process.exit(1);
}

// Basic structural assertions
const requiredTopLevel = [
  '_meta',
  'droneClasses',
  'effectors',
  'thresholds',
  'zones',
  'scoringWeights',
  'classificationMatrix',
  'chaos',
];

for (const key of requiredTopLevel) {
  if (!parsedConfig[key]) {
    console.error(`FATAL Config Validation: Missing required top-level key: "${key}"`);
    process.exit(1);
  }
}

// Compute SHA-256 hash
const hash = crypto.createHash('sha256').update(rawConfig).digest('hex');
const configHash = `sha256:${hash}`;

if (!fs.existsSync(targetDir)) {
  fs.mkdirSync(targetDir, { recursive: true });
}

const generatedTsContent = `// AUTO-GENERATED BY scripts/inline-config.mjs. DO NOT EDIT DIRECTLY.
// Generated at ${new Date().toISOString()}

export const CONFIG_HASH = ${JSON.stringify(configHash)};

export const APP_CONFIG = ${JSON.stringify(parsedConfig, null, 2)} as const;

export type AppConfig = typeof APP_CONFIG;
`;

fs.writeFileSync(targetFile, generatedTsContent, 'utf-8');
console.log(`[Config Pipeline] Successfully inlined config.json -> src/config/config.generated.ts (Hash: ${configHash.slice(0, 16)}...)`);
